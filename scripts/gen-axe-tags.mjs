// Regenerates src/data/axe-tags.js from the installed axe-core (WCAG / EN 301 549 / best-practice tags per
// rule). Run after upgrading axe-core: node scripts/gen-axe-tags.mjs (a unit test fails if it drifts).
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const axe = createRequire(import.meta.url)('axe-core');
const keep = (t) => /^(wcag\d{3,4}|wcag2a|wcag2aa|wcag21a|wcag21aa|wcag22aa|best-practice|EN-301-549v4|EN-9(\.\d+){3})$/.test(t);
export const tagsFor = () => Object.fromEntries(axe.getRules().map((r) => [r.ruleId, r.tags.filter(keep)]).sort(([a], [b]) => a.localeCompare(b)));

const body = Object.entries(tagsFor()).map(([id, tags]) => `  '${id}': ${JSON.stringify(tags).replace(/"/g, "'")},`).join('\n');
const out = `// Generated by scripts/gen-axe-tags.mjs from axe-core ${axe.version}. Do not edit by hand.\nexport default {\n${body}\n};\n`;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/axe-tags.js'), out);
  console.log(`src/data/axe-tags.js: ${Object.keys(tagsFor()).length} rules (axe-core ${axe.version})`);
}
